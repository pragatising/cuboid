// Generates src/components/core/Box/cssProperties.generated.ts: the names of every CSS property React.CSSProperties knows.
//
// Box takes any CSS property as a prop, so at runtime it must tell a style prop (`textAlign`) from a DOM attribute
// (`id`). Types cannot do that at runtime; this list can. It is generated from the same types (csstype, via
// React.CSSProperties) the props are typed with, so the two cannot drift, and `Box.test-d.tsx` fails if they do.
//
// Run it with `npm run generate:css-properties` after upgrading @types/react or csstype, and commit the result.
import ts from "typescript";
import path from "node:path";
import { writeFileSync } from "node:fs";

/** CSS properties that are also real DOM attributes (`<meta content>`, `translate="no"`, SVG geometry). They stay attributes: use `style` for the CSS. */
const ATTRIBUTES = ["content", "translate", "cx", "cy", "d", "r", "rx", "ry", "x", "y"];

const root = process.cwd();
const probe = path.join(root, "scripts/__probe.ts");
const host = ts.createCompilerHost({});
const original = host.getSourceFile.bind(host);
host.getSourceFile = (name, ...rest) =>
  name === probe
    ? ts.createSourceFile(
        name,
        `import type React from "react";
import type * as CSS from "csstype";
export type All = React.CSSProperties;
export type Standard = CSS.StandardShorthandProperties;
export type Vendor = CSS.VendorShorthandProperties;`,
        ts.ScriptTarget.ES2022,
      )
    : original(name, ...rest);

const program = ts.createProgram([probe], { jsx: ts.JsxEmit.ReactJSX, moduleResolution: ts.ModuleResolutionKind.Bundler, module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022, skipLibCheck: true, strict: true }, host);
const checker = program.getTypeChecker();
const source = program.getSourceFile(probe);
const names = (alias) => {
  const symbol = checker.getSymbolAtLocation(source).exports.get(alias);
  return checker.getPropertiesOfType(checker.getDeclaredTypeOfSymbol(symbol)).map((p) => p.name);
};

const all = names("All").filter((n) => !ATTRIBUTES.includes(n)).sort();
// A shorthand resets its longhands, so Box writes shorthands first. The shorthand sets are csstype's own.
const shorthandNames = new Set([...names("Standard"), ...names("Vendor")]);
const shorthands = all.filter((n) => shorthandNames.has(n));

const literal = (list) => `[\n${list.map((n) => `  "${n}",`).join("\n")}\n] as const`;
writeFileSync(
  path.join(root, "src/components/core/Box/cssProperties.generated.ts"),
  `// Generated by scripts/generate-css-properties.mjs: do not edit. Run \`npm run generate:css-properties\`.

/** Every CSS property Box takes as a prop (all of React.CSSProperties except the names that are also DOM attributes). */
export const CSS_PROPERTIES = ${literal(all)};

/** The CSS properties that are shorthands: Box writes them before the longhands, which refine them. */
export const CSS_SHORTHANDS: readonly string[] = ${literal(shorthands)};

/** CSS property names that stay DOM attributes on Box (\`content\`, \`translate\`, SVG geometry): use \`style\` for the CSS. */
export const CSS_ATTRIBUTE_NAMES = ${literal(ATTRIBUTES)};
`,
);
console.log(`${all.length} CSS properties, ${shorthands.length} shorthands, ${ATTRIBUTES.length} left as attributes`);
