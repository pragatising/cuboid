#!/usr/bin/env node
/**
 * Generates src/tokens/modes/dark/base-colors.json5 — the dark counterpart of
 * src/tokens/base/colors/light.json5, by CONTRAST MATCHING: every dark step is
 * given the same WCAG contrast ratio against the dark canvas that the
 * corresponding light step has against white, keeping the light step's hue and
 * chroma. Functional tokens reference base steps by role ("gray.11 is body
 * text"), so a palette that preserves each step's contrast role makes them
 * flip correctly with no per-token work. (A plain index mirror does not:
 * the light ramps are not symmetric, so e.g. muted text would come out far too
 * bright.)
 *
 * Run: node scripts/generators/generate-dark-palette.mjs
 * Review the emitted file, then hand-fix exceptions inline on the tokens that
 * need them (emphasis backgrounds, scrims, shadows, hard-coded colors) — not
 * here; this file is regenerated.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import JSON5 from "json5";
import Color from "colorjs.io";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const LIGHT = path.join(ROOT, "src/tokens/base/colors/light.json5");
const OUT = path.join(ROOT, "src/tokens/modes/dark/base-colors.json5");

const LIGHT_CANVAS = new Color("#ffffff");
const DARK_CANVAS = new Color("#1c1c1b"); // warm near-black, same family as the light grays
const SCALES_WITH_CHROMA_FLOOR = new Set(); // reserved: see CHROMA_FLOOR below
const CHROMA_FLOOR = 0; // tuned after review; tints at low contrast stay faint unless raised

const contrast = (a, b) => Color.contrast(a, b, "WCAG21");
const hex = (c) => c.to("srgb").toGamut({ method: "css" }).toString({ format: "hex", collapse: false });

/** Lightest/darkest-first search: find the OKLCH lightness giving `target` contrast against the dark canvas. */
function matchContrast(hue, chroma, target) {
  let lo = DARK_CANVAS.oklch.l;
  let hi = 1;
  let best = null;
  for (let i = 0; i < 40; i++) {
    const l = (lo + hi) / 2;
    const candidate = new Color("oklch", [l, chroma, Number.isNaN(hue) ? 0 : hue]).toGamut({ method: "css" });
    if (contrast(candidate, DARK_CANVAS) < target) lo = l;
    else hi = l;
    best = candidate;
  }
  return best;
}

function darkStep(lightHex) {
  const light = new Color(lightHex);
  const target = contrast(light, LIGHT_CANVAS);
  const { c, h } = light.to("oklch");
  return hex(matchContrast(h, Math.max(c, CHROMA_FLOOR), Math.max(target, 1)));
}

const scales = JSON5.parse(fs.readFileSync(LIGHT, "utf8")).base.color;
const out = { base: { color: {} } };

for (const [name, scale] of Object.entries(scales)) {
  // Only the opaque numbered ramps are generated; black/white/transparent/alpha/overlay/shadow are exceptions, and so is highlight (its markers carry their own dark values).
  if (["black", "white", "transparent", "grayAlpha", "shadowAlpha", "overlay", "highlight"].includes(name)) continue;
  out.base.color[name] = {};
  for (const [step, token] of Object.entries(scale)) {
    out.base.color[name][step] = { $value: name === "gray" && step === "0" ? hex(DARK_CANVAS) : darkStep(token.$value) };
  }
}

const header = `// GENERATED by scripts/generators/generate-dark-palette.mjs — do not edit by hand.\n// Contrast-matched dark counterpart of base/colors/light.json5. Applied in dark mode only.\n`;
fs.writeFileSync(OUT, header + JSON5.stringify(out, null, 2) + "\n");
console.log(`wrote ${path.relative(ROOT, OUT)}`);
