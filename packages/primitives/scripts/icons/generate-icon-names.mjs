#!/usr/bin/env node
/**
 * Generate the canonical `IconName` union from Material Symbols' own manifest —
 * NOT from Figma. Figma names are a design-tool concern (see sync-icons.mjs);
 * this file is the single source of truth for what names are valid, and other
 * icon libraries (a Lucide adapter, a custom SVG set) must resolve against this
 * same name set rather than defining their own.
 *
 *   node scripts/generate-icon-names.mjs
 *   (also invoked by `npm run icons:sync`)
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const ROOT = path.resolve(import.meta.dirname, "../..");
// Resolved through Node (the package is hoisted to the workspace root), not a hard-coded node_modules path.
const ICON_INDEX_FILE = path.join(
  path.dirname(createRequire(import.meta.url).resolve("@material-symbols-svg/react/package.json")),
  "dist/metadata/icon-index.json"
);
const OUTPUT_DIR = path.join(ROOT, "icons/material");
const OUTPUT_JS = path.join(OUTPUT_DIR, "iconNames.generated.js");
const OUTPUT_DTS = path.join(OUTPUT_DIR, "iconNames.generated.d.ts");

export function loadCanonicalIconNames() {
  const index = JSON.parse(fs.readFileSync(ICON_INDEX_FILE, "utf8"));
  return Object.keys(index).sort();
}

const HEADER = (names) => [
  "/**",
  " * AUTO-GENERATED by `npm run icons:sync` (scripts/icons/generate-icon-names.mjs) — do not edit by hand.",
  " *",
  " * Canonical icon name set, sourced directly from Material Symbols' own",
  " * manifest (`@material-symbols-svg/react/dist/metadata/icon-index.json`),",
  " * not from Figma. Names are the underscore_case `name` field from that",
  " * manifest (e.g. `account_circle`) — this IS the glyph's font ligature text,",
  " * which the Material Symbols icon library relies on directly.",
  " *",
  ` * ${names.length} names.`,
  " */",
];

/** Plain ESM: this package ships JavaScript, never raw TypeScript, to its consumers. */
function generateJs(names) {
  return [
    ...HEADER(names),
    "/** Runtime membership check / iteration — same set as the `IconName` type in the .d.ts. */",
    "export const ICON_NAMES = [",
    ...names.map((name) => `  "${name}",`),
    "];",
    "",
    "const ICON_NAME_SET = new Set(ICON_NAMES);",
    "",
    "export function isIconName(value) {",
    "  return ICON_NAME_SET.has(value);",
    "}",
    "",
  ].join("\n");
}

function generateDts(names) {
  return [
    ...HEADER(names),
    "export type IconName =",
    ...names.map((name) => `  | "${name}"`),
    ";",
    "",
    "export declare const ICON_NAMES: readonly IconName[];",
    "export declare function isIconName(value: string): value is IconName;",
    "",
  ].join("\n");
}

/** Writes both generated files; shared with sync-icons.mjs so there is one generator. */
export function writeIconNames(names) {
  fs.writeFileSync(OUTPUT_JS, generateJs(names));
  fs.writeFileSync(OUTPUT_DTS, generateDts(names));
  return [OUTPUT_JS, OUTPUT_DTS];
}

function main() {
  const names = loadCanonicalIconNames();
  for (const file of writeIconNames(names)) console.log(`Generated ${names.length} icon names → ${path.relative(ROOT, file)}`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
